/// <summary>
/// PRC's compressed doubles (ISO 14739-1, "WriteDouble"): a prefix code names either one of a few
/// frequent values or an exponent; an exponent is followed by the sign and only the mantissa bytes
/// that differ from their neighbours. The code table is the standard's, as prc-rs (MIT, Kristóf
/// Ralovich) transcribed it.
/// </summary>
internal static class PrcDoubles
{
    public static double Read(PrcBitReader r)
    {
        var table = Table.Value;
        uint code = 0;
        for (var length = 1; length <= 22; length++)
        {
            code = (code << 1) | (r.Bit() ? 1u : 0u);
            if (!table.TryGetValue(Key(length, code), out var entry)) continue;

            // A frequent double: zero is complete; the others are followed by their sign.
            if (entry >= 0)
            {
                var bits = FrequentValues[entry];
                if (length == 2 && code == 1) return BitConverter.UInt64BitsToDouble(bits);
                if (r.Bit()) bits |= 1UL << 63;
                return BitConverter.UInt64BitsToDouble(bits);
            }
            return Mantissa(r, ~entry);
        }
        throw new PrcFormatException("PRC double code not in the table");
    }

    private static double Mantissa(PrcBitReader r, int exponent)
    {
        Span<byte> b = stackalloc byte[8];
        // The table's value for the largest exponent is a quiet NaN, not an infinity.
        BitConverter.TryWriteBytes(b, exponent == 2047 ? 0x7FF8_0000_0000_0000UL : (ulong)exponent << 52);
        if (r.Bit()) b[7] |= 0x80;
        if (!r.Bit()) return BitConverter.ToDouble(b);

        b[6] |= (byte)r.Bits(4);
        int last = 0, current = 5;
        while (current >= last)
        {
            if (r.Bit())
            {
                b[current] = r.Byte();
            }
            else
            {
                // Not a new byte: a copy of one already read, or the rest all the same.
                var offset = (int)r.Bits(3);
                if (offset == 0)
                {
                    var same = b[current + 1];
                    for (; current >= last; current--) b[current] = same;
                    break;
                }
                if (offset == 6)
                {
                    var same = b[current + 1];
                    for (last++; current >= last; current--) b[current] = same;
                    b[current] = r.Byte();
                    break;
                }
                if (current + offset >= 8) throw new PrcFormatException("PRC double damaged");
                b[current] = b[current + offset];
            }
            current--;
        }
        return BitConverter.ToDouble(b);
    }

